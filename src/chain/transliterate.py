_LOANWORD_RE = re.compile("|".join(re.escape(k) for k in sorted(_LOANWORDS, key=len, reverse=True)))


def _syllable_to_kana(ch: str, mid_word: bool) -> str:
    code = ord(ch)
    i = code - 0xAC00
    cho = _CHO[i // (21 * 28)]
    jung = _JUNG[(i % (21 * 28)) // 28]
    jong = _JONG[i % 28]
    sei, daku = _CHO_ROW.get(cho, ("", ""))
    row = daku if (mid_word and daku) else sei
    vkey = _VOWEL.get(jung, "a")
    kana = _ROWS.get(row, _ROWS[sei]).get(vkey) or _ROWS[sei].get(vkey, "")
    return kana, _JONG_KANA.get(jong, "")


def hangul_to_katakana(text: str) -> str:
    """한글이 섞인 문자열을 가타카나 근사 음역으로. 비한글(영문·숫자·기호)은 유지."""
    if not text:
        return ""
    # 1) 외래어/브랜드 단어를 먼저 가타카나로 치환(자리표시자로 보호)
    holders: list[str] = []

    def _stash(m: re.Match) -> str:
        holders.append(_LOANWORDS[m.group(0)])
        return f"\x00{len(holders) - 1}\x00"

    staged = _LOANWORD_RE.sub(_stash, text)

    # 2) 남은 한글을 음절 단위 음역
    out: list[str] = []
    prev_hangul = False
    n = len(staged)
    for idx, ch in enumerate(staged):
        if "가" <= ch <= "힣":
            kana, jong_kana = _syllable_to_kana(ch, prev_hangul)
            out.append(kana)
            if jong_kana == "ッ":
                nxt = staged[idx + 1] if idx + 1 < n else ""
                if not ("가" <= nxt <= "힣"):  # 단어 끝 ッ 생략
                    jong_kana = ""
            out.append(jong_kana)
            prev_hangul = True
        else:
            out.append(ch)
            prev_hangul = False
    result = "".join(out)

    # 3) 자리표시자 복원
    def _restore(m: re.Match) -> str:
        return holders[int(m.group(1))]

    return re.sub(r"\x00(\d+)\x00", _restore, result)
